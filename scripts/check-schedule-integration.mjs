import assert from 'node:assert/strict';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { chromium } from '@playwright/test';
import fastifyStatic from '@fastify/static';
import { buildApp } from '../src/server/app.ts';

// Fresh browser profiles and a temporary database only. Never use learning data.
const temporary = await mkdtemp(path.join(tmpdir(), 'nihongo-schedule-'));
const app = buildApp({ dataDir: temporary });
const key = 'weekly-rhythm-planner-v1';
let browser;
try {
  await app.register(fastifyStatic, { root: path.resolve('dist') });
  await app.listen({ host: '127.0.0.1', port: 0 });
  const origin = `http://127.0.0.1:${app.server.address().port}`;
  browser = await chromium.launch({ headless: true, ...(process.platform === 'win32' ? { channel: 'msedge' } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1080 }, acceptDownloads: true });
  await context.route('**/*', route => new URL(route.request().url()).origin === origin ? route.continue() : route.abort());
  const page = await context.newPage();
  page.setDefaultTimeout(7000);
  const errors = [];
  page.on('pageerror', error => { errors.push(error.message); console.error('BROWSER ERROR', error.message); });
  page.on('dialog', dialog => dialog.accept());
  await page.goto(origin);
  await page.getByRole('button', { name: '日程表', exact: true }).click();
  assert.equal(new URL(page.url()).hash, '#schedule');
  const frame = page.locator('.schedule-native');
  await frame.locator('.day').first().waitFor();
  assert.equal(await frame.locator('.day').count(), 7);
  assert.equal(await frame.locator('.brand').isVisible(), false);
  assert.equal(await frame.locator('.hero').isVisible(), false);
  const plan = () => page.evaluate(key => JSON.parse(localStorage.getItem(key)), key);
  const before = await plan();
  assert.ok(before.events.length > 0);
  const totalMinutes = before.events.filter(item => item.category !== 'routine').reduce((total, item) => total + item.end - item.start, 0);
  const readSummary = async () => {
    const text = await frame.locator('.summary-heading > strong').innerText();
    return Number(text.match(/(\d+)\s*小时/)?.[1] ?? 0) * 60 + Number(text.match(/(\d+)\s*分钟/)?.[1] ?? 0);
  };
  assert.equal(await page.locator('iframe').count(), 0);
  assert.equal(await page.locator('.schedule-page .page-heading').count(), 0);
  const calendarTop = await frame.locator('.planner').boundingBox();
  const appTopbar = await page.locator('.main-area > .topbar').boundingBox();
  assert.ok(calendarTop.y - appTopbar.y - appTopbar.height <= 25);
  assert.equal(await frame.locator('#board-scroll').evaluate(node => node.scrollHeight <= node.clientHeight + 1), true);
  const boardBounds = await frame.locator('#board').boundingBox();
  const summaryBounds = await frame.locator('#stats').boundingBox();
  assert.ok(summaryBounds.y > boardBounds.y + boardBounds.height);
  assert.ok(await frame.locator('.summary-segment').count() > 0);
  assert.equal(await readSummary(), totalMinutes);
  assert.ok(Math.abs(await frame.locator('.summary-segment').evaluateAll(nodes => nodes.reduce((sum, node) => sum + parseFloat(node.style.width), 0)) - 100) < .01);
  console.log('PASS native calendar, whole-page scrolling and bottom visual time summary');

  await frame.locator('#add-event').click();
  await frame.locator('#event-title').fill('集成验收：日语复习');
  await frame.locator('#event-category').selectOption('japanese');
  await frame.locator('#event-day').selectOption('5');
  await frame.locator('#event-start').fill('19:00');
  await frame.locator('#event-end').fill('19:30');
  await frame.locator('#event-notes').fill('保留备注');
  await frame.locator('#event-form button[type=submit]').click();
  await frame.locator('#event-dialog').waitFor({ state: 'hidden' });
  let item = (await plan()).events.find(item => item.title === '集成验收：日语复习');
  assert.equal(item.notes, '保留备注');
  assert.equal(await readSummary(), totalMinutes + 30);
  const id = item.id;
  await page.getByRole('button', { name: '50课地图', exact: true }).click();
  await page.getByRole('button', { name: '日程表', exact: true }).click();
  await frame.locator('.day').first().waitFor();
  assert.ok((await plan()).events.some(item => item.id === id));
  await page.reload();
  await frame.locator('.day').first().waitFor();
  const card = frame.locator(`.event[data-event-id="${id}"]`).first();
  await card.click();
  await frame.locator('#event-title').fill('集成验收：编辑完成');
  await frame.locator('#event-form button[type=submit]').click();
  await frame.locator('#event-dialog').waitFor({ state: 'hidden' });
  assert.equal((await plan()).events.find(item => item.id === id).title, '集成验收：编辑完成');
  await card.click();
  await frame.locator('#delete-event').click();
  assert.equal((await plan()).events.some(item => item.id === id), false);
  await frame.locator('#undo-btn').click();
  assert.ok((await plan()).events.some(item => item.id === id));
  console.log('PASS add, edit, delete, undo, route switching and reload persistence');

  await frame.locator('#show-routines').check();
  await frame.locator('#fold-routines').check();
  assert.equal((await plan()).view.foldRoutines, true);
  await frame.locator('[data-filter="japanese"]').click();
  assert.equal(await frame.locator('.event:not([data-category="japanese"]):not([data-category="routine"])').count(), 0);
  await frame.locator('[data-filter="all"]').click();
  await frame.locator('#fold-routines').uncheck();
  assert.equal(await frame.locator('.week-nav').isVisible(), false);
  assert.equal(await frame.locator('.day-date:visible').count(), 0);
  assert.equal(await frame.locator('.day.today').count(), 0);
  assert.equal(await frame.locator('.summary-heading h2').innerText(), '每周时间分配');
  await frame.locator('#add-event').click();
  assert.deepEqual(await frame.locator('#event-day option').allTextContents(), ['周一','周二','周三','周四','周五','周六','周日']);
  await frame.locator('#cancel-dialog').click();
  assert.ok((await plan()).events.some(item => item.id === id));
  console.log('PASS category filtering, routines, folding and a recurring plan without calendar dates');

  const downloadEvent = page.waitForEvent('download');
  await frame.locator('#export-btn').click();
  const download = await downloadEvent;
  const stream = await download.createReadStream();
  const chunks = [];
  for await (const chunk of stream) chunks.push(chunk);
  const backup = Buffer.concat(chunks);
  assert.ok(JSON.parse(backup).events.some(item => item.id === id));
  await frame.locator('#import-file').setInputFiles({ name: 'schedule.json', mimeType: 'application/json', buffer: backup });
  await page.waitForFunction(() => !document.querySelector('.schedule-native')?.shadowRoot?.querySelector('#import-file')?.value);
  assert.ok((await plan()).events.some(item => item.id === id));
  await page.evaluate(() => { window.print = () => { document.body.dataset.printed = 'yes'; }; });
  await frame.locator('#print-btn').click();
  assert.equal(await page.locator('body').getAttribute('data-printed'), 'yes');
  console.log('PASS export, import and print action');

  // Import artificial tasks to verify pointer coordinates across the scoped
  // document, including when the parent and timeline have both scrolled.
  const pointerFixture = { ...(await plan()), events: [
    { id: 'drag-a', title: '拖拽验收', day: 0, category: 'japanese', start: 600, end: 630, notes: '' },
    { id: 'drag-b', title: '多选验收', day: 0, category: 'japanese', start: 660, end: 690, notes: '' },
  ], view: { filter: 'all', showRoutines: false, foldRoutines: false } };
  await frame.locator('#import-file').setInputFiles({ name: 'pointer.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(pointerFixture)) });
  const draggingCard = frame.locator('.event[data-event-id="drag-a"]');
  await draggingCard.scrollIntoViewIfNeeded();
  let bounds = await draggingCard.boundingBox();
  const target = await frame.locator('.day[data-day="1"] .day-list').boundingBox();
  await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
  await page.mouse.down();
  await page.waitForTimeout(650);
  await page.mouse.move(target.x + target.width / 2, bounds.y + bounds.height / 2, { steps: 12 });
  await page.mouse.up();
  assert.equal((await plan()).events.find(item => item.id === 'drag-a').day, 1);
  assert.equal((await plan()).events.find(item => item.id === 'drag-a').end - (await plan()).events.find(item => item.id === 'drag-a').start, 30);
  await frame.locator('#undo-btn').click();
  assert.equal((await plan()).events.find(item => item.id === 'drag-a').day, 0);
  await draggingCard.click({ modifiers: ['Control'] });
  await frame.locator('.event[data-event-id="drag-b"]').click({ modifiers: ['Control'] });
  assert.equal(await frame.locator('.event.is-selected').count(), 2);
  await frame.locator('#selection-copy').click();
  await frame.locator('#selection-clear').click();
  await draggingCard.click({ button: 'right' });
  await frame.locator('#context-copy').click();
  bounds = await draggingCard.boundingBox();
  const pasteDay = await frame.locator('.day[data-day="2"] .day-list').boundingBox();
  await page.mouse.click(pasteDay.x + pasteDay.width / 2, bounds.y + bounds.height / 2, { button: 'right' });
  await frame.locator('#context-paste').click();
  assert.equal((await plan()).events.length, 3);
  assert.equal((await plan()).events.filter(item => item.title === '拖拽验收').length, 2);
  console.log('PASS long-press drag across days, undo, multiple selection and context copy/paste');

  const largeText = page.getByRole('button', { name: '大字', exact: true });
  if (await largeText.getAttribute('aria-pressed') === 'true') {
    await largeText.click();
    await page.locator('.schedule-native:not(.large-text)').waitFor();
  }
  await largeText.click();
  await page.locator('.schedule-native.large-text').waitFor();
  await page.getByRole('button', { name: '沉浸模式', exact: true }).click();
  const nav = page.getByRole('combobox', { name: '导航', exact: true });
  assert.equal(await nav.inputValue(), 'schedule');
  await nav.selectOption('lessons');
  await nav.selectOption('schedule');
  await frame.locator('.day').first().waitFor();
  await page.getByRole('button', { name: '退出沉浸模式', exact: true }).click();
  await frame.locator('#import-file').setInputFiles({ name: 'original-fixture.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify(before)) });
  await mkdir('test-results', { recursive: true });
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: 'test-results/schedule-desktop.png', fullPage: true });
  console.log('PASS large text and immersive navigation');

  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  assert.equal(await page.locator('.sidebar nav > button, .sidebar nav > .special-nav > button').count(), 5);
  const navBounds = await page.getByRole('button', { name: '日程表', exact: true }).boundingBox();
  assert.ok(navBounds.x >= 0 && navBounds.x + navBounds.width <= 390);
  const settingsBounds = await page.getByRole('button', { name: '设置', exact: true }).boundingBox();
  assert.equal(settingsBounds.y, navBounds.y);
  await frame.locator('#add-event').click();
  const dialog = await frame.locator('#event-dialog').boundingBox();
  const calendarBounds = await page.locator('.schedule-native').boundingBox();
  assert.ok(dialog.width <= calendarBounds.width);
  assert.ok(dialog.y >= 0 && dialog.y + dialog.height <= 844 - 80);
  await frame.locator('#cancel-dialog').click();
  await page.evaluate(() => { document.activeElement?.blur(); window.scrollTo(0, 0); });
  await page.screenshot({ path: 'test-results/schedule-mobile.png', fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS mobile navigation, layout and editor; no browser errors');
  await context.close();

  const touchContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  await touchContext.addInitScript(({ key, fixture }) => localStorage.setItem(key, JSON.stringify(fixture)), { key, fixture: pointerFixture });
  const touchPage = await touchContext.newPage();
  touchPage.on('pageerror', error => errors.push(error.message));
  await touchPage.goto(origin + '/#schedule');
  const touchCard = touchPage.locator('.event[data-event-id="drag-a"]');
  await touchCard.waitFor();
  const cdp = await touchContext.newCDPSession(touchPage);
  const touch = (type, x, y) => cdp.send('Input.dispatchTouchEvent', { type, touchPoints: type === 'touchEnd' ? [] : [{ x, y, id: 1 }] });
  await touchCard.scrollIntoViewIfNeeded();
  let touchBounds = await touchCard.boundingBox();
  let x = touchBounds.x + touchBounds.width / 2, y = touchBounds.y + touchBounds.height / 2;
  const pageScroll = await touchPage.evaluate(() => scrollY);
  await touch('touchStart', x, y);
  await touch('touchMove', x, y - 20);
  await touch('touchMove', x, y - 100);
  await touch('touchEnd');
  assert.ok(await touchPage.evaluate(() => scrollY) > pageScroll);
  assert.equal(await touchPage.locator('#board-scroll').evaluate(node => node.scrollTop), 0);
  assert.equal((await touchPage.evaluate(key => JSON.parse(localStorage.getItem(key)), key)).events.find(item => item.id === 'drag-a').day, 0);
  await touchCard.scrollIntoViewIfNeeded();
  touchBounds = await touchCard.boundingBox();
  x = touchBounds.x + touchBounds.width / 2; y = touchBounds.y + touchBounds.height / 2;
  const touchTarget = await touchPage.locator('.day[data-day="1"] .day-list').boundingBox();
  await touch('touchStart', x, y);
  await touchPage.waitForTimeout(550);
  await touch('touchMove', touchTarget.x + touchTarget.width / 2, y);
  await touch('touchEnd');
  const moved = (await touchPage.evaluate(key => JSON.parse(localStorage.getItem(key)), key)).events.find(item => item.id === 'drag-a');
  assert.equal(moved.day, 1);
  assert.equal(moved.end - moved.start, 30);
  assert.deepEqual(errors, []);
  console.log('PASS actual mobile touch: short swipe scrolls the page; long press drags across days');
  await touchContext.close();
} finally {
  await browser?.close();
  await app.close();
  await rm(temporary, { recursive: true, force: true });
}
